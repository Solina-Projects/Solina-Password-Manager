package app.solina.passwordmanager.core.crypto

/**
 * چند خزانه (فاز ۴، آیتم ۷) — به‌تعویق‌افتاده، با دلیل دقیق. این فایل فقط طراحی است؛
 * هیچ کدی از مسیر باز کردن خزانهٔ فعلی را عوض نمی‌کند.
 *
 * ══════════════════════════ طراحی پیشنهادی (برای فاز جدا) ══════════════════════════
 *
 * ۱) هر خزانه یک هدر جدا (VaultHeader) با salt تصادفیِ خودش دارد؛ فایل‌ها:
 *    vault-default/ (فعلی، دست‌نخورده) و vault-<id>/ برای خزانه‌های بعدی.
 *    کلید خزانه (VK) هر خزانه جداگانه با رمز اصلی بسته می‌شود؛ salt متفاوت یعنی
 *    KEK متفاوت، و AAD/info بسته‌بندی باید شناسهٔ خزانه را هم داشته باشد
 *    (جداسازی دامنه: "solina/wrap/pw/v1" + vaultId) تا دو خزانه با رمز و salt
 *    یکسان هم قابل اشتباه نباشند.
 *
 * ۲) بازیابی: BIP-39 جداگانه برای هر خزانه (۲۴ کلمهٔ مخصوص همان خزانه).
 *    انتخاب: هر خزانه ۲۴ کلمهٔ خودش را دارد — چون اگر یک عبارت بازیابی لو برود،
 *    فقط همان خزانه لو می‌رود نه همه. هزینه‌اش این است که کاربر باید N عبارت را
 *    جدا نگه دارد؛ این هزینه آگاهانه پذیرفته شده است (ایزولاسیون مهم‌تر از راحتی است).
 *
 * ۳) همگام‌سازی و بکاپ: رکورد SLNI امروز شناسهٔ خزانه ندارد؛ چندخزانه‌ای یعنی
 *    افزودن vaultId به رکورد همگام‌سازی (تغییر قالب — در این فاز ممنوع بود) و
 *    بکاپ جداگانه برای هر خزانه (یا بکاپ v2 با بخش‌بندی per-vault).
 *
 * ۴) مهاجرت: خزانهٔ فعلی بدون هیچ رمزگذاریِ دوباره، «خزانهٔ پیش‌فرض» می‌شود؛
 *    هیچ آیتمی جابه‌جا یا دوباره رمز نمی‌شود.
 *
 * ══════════════════════════ چرا در این فاز انجام نشد (دلیل دقیق) ══════════════════════════
 *
 * - قالب هدر خزانه v1 یک چیدمان باینری با اندازهٔ ثابت است (MAGIC + نسخه + KDF +
 *   salt + دو کلید بسته‌شده) و VaultHeader.decode نسخهٔ غیر از ۱ را رد می‌کند؛
 *   چندخزانه‌ای یا به هدر v2 نیاز دارد یا به فایل‌های هدر موازی — هر دو یعنی
 *   بازنویسی VaultFiles و VaultRepository و AppContainer و UI تعویض خزانه.
 * - بدون تست مهاجرت روی دادهٔ واقعیِ تک‌خزانه‌ای، کوچک‌ترین خطا در این بازنویسی
 *   می‌تواند کاربر را برای همیشه از خزانهٔ فعلی‌اش بیرون بیندازد؛ این تنها چیزی
 *   است که هرگز نباید بشکند. پس به‌جای یک چندخزانه‌ایِ نیمه‌امن، تعویقِ کامل
 *   انتخاب شد: چندخزانه‌ایِ خراب بدتر از نداشتنِ آن است.
 * - پیش‌نیاز فاز جدا: تست مهاجرت (ساخت خزانهٔ v1 واقعی → افزودن خزانهٔ دوم →
 *   باز کردن هر دو با رمز اصلی و ۲۴ کلمهٔ هرکدام → بکاپ/بازیابی هر خزانه جدا).
 */
object MultiVaultDesign {
    /** بازیابی جداگانه برای هر خزانه (۲۴ کلمهٔ مخصوص همان خزانه). */
    const val RECOVERY_PER_VAULT = true

    /** سقف پیشنهادی تعداد خزانه‌ها (برای اینکه UI و بکاپ قابل مدیریت بماند). */
    const val MAX_VAULTS = 5

    /** شناسهٔ خزانهٔ فعلی که بدون مهاجرت، «پیش‌فرض» می‌شود. */
    const val DEFAULT_VAULT_ID = "default"

    /** پیشوند info برای جداسازی دامنهٔ بسته‌بندی کلید هر خزانه (به VaultCrypto اضافه شود). */
    const val WRAP_INFO_PREFIX = "solina/wrap/pw/v1/vault:"
}
